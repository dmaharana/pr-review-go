package review

import (
	"fmt"
	"strings"

	"pr-review-go/internal/domain"
)

// FormatReviewMarkdown renders a full markdown review report.
func FormatReviewMarkdown(out *domain.ReviewOutput) string {
	var sb strings.Builder

	// Header badge
	var badge string
	switch out.Verdict {
	case domain.VerdictChangesRequired:
		badge = "❌ **Changes Required**"
	case domain.VerdictNeedsReview:
		badge = "⚠️ **Needs Review**"
	case domain.VerdictNoConcernsFound:
		badge = "✅ **No Concerns Found**"
	default:
		badge = "ℹ️ **Review Completed**"
	}

	sb.WriteString(fmt.Sprintf("## PR Review: %s\n\n", badge))
	sb.WriteString(fmt.Sprintf("**Summary:** %s\n\n", out.Summary))
	sb.WriteString(fmt.Sprintf("- **Risk Level:** %s\n", strings.ToUpper(out.RiskAssessment)))
	if out.EffortToReview > 0 {
		sb.WriteString(fmt.Sprintf("- **Estimated Effort to Review:** %d / 5\n", out.EffortToReview))
	}
	if len(out.PriorityFiles) > 0 {
		sb.WriteString(fmt.Sprintf("- **Priority Files to Inspect:** `%s`\n", strings.Join(out.PriorityFiles, "`, `")))
	}
	sb.WriteString("\n")

	if len(out.Findings) > 0 {
		sb.WriteString("### Key Findings\n\n")
		sb.WriteString("| Severity | File | Lines | Issue |\n")
		sb.WriteString("| :--- | :--- | :--- | :--- |\n")
		for _, f := range out.Findings {
			lines := fmt.Sprintf("%d-%d", f.StartLine, f.EndLine)
			if f.StartLine == f.EndLine {
				lines = fmt.Sprintf("%d", f.StartLine)
			}
			sb.WriteString(fmt.Sprintf("| **%s** | `%s` | %s | %s |\n",
				strings.ToUpper(string(f.Severity)), f.File, lines, f.IssueTitle))
		}
		sb.WriteString("\n")

		sb.WriteString("<details><summary><b>View Detailed Finding Descriptions</b></summary>\n\n")
		for i, f := range out.Findings {
			sb.WriteString(fmt.Sprintf("#### %d. [%s] %s (`%s:%d-%d`)\n",
				i+1, strings.ToUpper(string(f.Severity)), f.IssueTitle, f.File, f.StartLine, f.EndLine))
			sb.WriteString(f.Description + "\n\n")
			if f.HasCodeSuggestion() {
				sb.WriteString("**Proposed Fix:**\n")
				sb.WriteString("```suggestion\n" + f.SuggestedCode + "\n```\n\n")
			}
		}
		sb.WriteString("</details>\n\n")
	} else {
		sb.WriteString("### Key Findings\nNo actionable issues or defects identified in this diff.\n\n")
	}

	sb.WriteString("---\n*Generated by `pr-review-go`*")
	return sb.String()
}

// FormatDescribeMarkdown renders the PR description markdown.
func FormatDescribeMarkdown(desc *domain.DescribeOutput) string {
	var sb strings.Builder
	sb.WriteString(fmt.Sprintf("### %s\n\n", desc.Title))
	sb.WriteString(fmt.Sprintf("**Type:** `%s`\n\n", desc.Type))
	sb.WriteString(fmt.Sprintf("### Overview\n%s\n\n", desc.Summary))

	if desc.Walkthrough != "" {
		sb.WriteString(fmt.Sprintf("### Walkthrough\n%s\n\n", desc.Walkthrough))
	}

	if len(desc.KeyChanges) > 0 {
		sb.WriteString("### Key Changes\n")
		for _, change := range desc.KeyChanges {
			sb.WriteString(fmt.Sprintf("- %s\n", change))
		}
		sb.WriteString("\n")
	}

	if len(desc.SuggestedTags) > 0 {
		sb.WriteString(fmt.Sprintf("**Suggested Tags:** `%s`\n\n", strings.Join(desc.SuggestedTags, "`, `")))
	}

	sb.WriteString("---\n*Generated by `pr-review-go`*")
	return sb.String()
}
